package com.arkiv.player.data.plugin

import org.json.JSONArray
import org.json.JSONObject
import java.security.MessageDigest

/** [NuvioPluginConverter.convert]'s result: a ready-to-ship `plugin.js` + `kino-plugin.json` pair. */
data class NuvioConversionResult(val script: String, val manifestJson: String, val hosts: List<String>, val warnings: List<String>)

/**
 * Turns one Nuvio scraper into a Kino plugin (spec §5): the compat shim ([PluginPrelude.nuvioShim])
 * + the scraper's own source, byte for byte but wrapped in its own IIFE, + a small adapter mapping
 * Nuvio's `getStreams(tmdbId, mediaType, season, episode)` onto Kino's `search`/`resolve` (spec §6).
 * Pure and offline -- every network call (fetching the scraper's raw `.js`, the optional
 * `domains.json`) happens in `NuvioPluginInstaller`, before this runs.
 *
 * The whole result loads as ONE ES module (`PluginRuntime.open`'s `js.addModule`), so the shim's own
 * top-level `module`/`exports`/`require`/`fetch` and the scraper's own top-level code can't just be
 * concatenated at the same top level: two top-level declarations of the same name in one module
 * scope make QuickJS reject the WHOLE script with `SyntaxError: invalid redefinition of global
 * identifier` -- and a bundled/minified scraper redeclaring one of those four names is common. The
 * scraper's source instead runs inside an isolating IIFE with its own private `module`/`exports`
 * (exposed to the adapter as `__nuvioModuleExports`), so its own top-level declarations only ever
 * SHADOW the shim's in a nested scope -- never a redefinition, never an error. A scraper that
 * declares its own top-level `require` does lose access to the shim's `require('cheerio')`/
 * `require('crypto-js')` from inside its own body (shadowed), but that's rare in practice and far
 * better than the hard syntax error this replaces.
 *
 * The generated manifest always names the literal `"plugin.js"` as its `entry`: that file never
 * existed upstream (this converter builds it fresh), so whoever installs the result must write the
 * generated bytes under that name -- `PluginAddress.rawUrl(manifest.entry)` must NOT be used to
 * locate it, since it never exists at that URL. The original scraper's own path
 * ([NuvioScraperEntry.filename]) is only ever fetched separately, as input to [convert].
 */
object NuvioPluginConverter {
    /**
     * cheerio calls that walk the DOM via a parent/sibling pointer: [PluginHtml]'s flat match list has
     * no tree to walk, so these have no translation and always throw (see `nuvio-shim.js`).
     * `.find(sel)` is NOT here: the shim answers it by re-selecting inside each matched element's own
     * inner HTML, which works for the vast majority of real scraper code (`$(el).find("a[href]")`).
     * Only checked when the scraper uses cheerio at all: `.next(`/`.children(` alone also match
     * esbuild's own `generator.next(...)` helper and plain array/object property names.
     */
    private val CHEERIO_TRAVERSAL = Regex("""\.(parent|parents|next|prev|siblings|closest|children)\s*\(""")

    fun convert(
        scraper: NuvioScraperEntry,
        scraperSource: String,
        repoSlug: String,
        tmdbApiKey: String,
        remoteHosts: NuvioRemoteHosts = NuvioRemoteHosts.NONE,
    ): NuvioConversionResult {
        val slug = scraper.id.lowercase().replace(Regex("[^a-z0-9-]"), "-").trim('-').ifEmpty { "scraper" }
        val hash = sha256Hex(repoSlug.toByteArray(Charsets.UTF_8)).take(6)
        // The hash disambiguates the same scraper id across two different Nuvio repos: its space is
        // reserved FIRST, so a long slug is what shrinks -- capping the whole "nuvio-<slug>-<hash>"
        // string at PluginManifest's 40-char id limit from the right would otherwise truncate into
        // (or entirely erase) the hash for a sanitized slug of ~34+ characters.
        val idPrefix = "nuvio-"
        val idSuffix = "-$hash"
        val maxSlugLen = (40 - idPrefix.length - idSuffix.length).coerceAtLeast(1)
        val id = idPrefix + slug.take(maxSlugLen).trimEnd('-').ifEmpty { "s" } + idSuffix

        // Priority order BEFORE the cap: the remote list's entries this scraper names (its current,
        // rotated domain), then its own literals, then the rest of a shared remote list. Every
        // candidate is validated first, so no garbage ever occupies one of the MAX_HOSTS slots.
        val candidates = (remoteHosts.preferred + NuvioHostExtractor.extractHosts(scraperSource) + remoteHosts.others)
            .filter(NuvioHostExtractor::isPlausibleHost)
            .distinct()
        val hosts = candidates.take(ManifestParser.MAX_HOSTS)

        val warnings = buildList {
            if ("cheerio" in scraperSource && CHEERIO_TRAVERSAL.containsMatchIn(scraperSource)) {
                add("Aviso: usa funciones de cheerio (.parent/.next/.siblings…) que podrían no funcionar del todo.")
            }
            if (candidates.size > ManifestParser.MAX_HOSTS) {
                add("Aviso: se detectaron más de ${ManifestParser.MAX_HOSTS} dominios; algunos quedaron fuera.")
            }
        }

        val shim = PluginPrelude.nuvioShim.replace("__NUVIO_TMDB_API_KEY__", tmdbApiKey)
        // The scraper's own top-level code runs inside an IIFE, never spliced in at the same top
        // level as the shim: see this object's KDoc for why (QuickJS module-scope collisions).
        val wrapped = "var __nuvioModuleExports = (function () {\n" +
            "var module = { exports: {} };\n" +
            "var exports = module.exports;\n" +
            scraperSource +
            "\nreturn module.exports;\n})();\n"
        val script = shim + "\n\n" + wrapped + "\n" + ADAPTER

        val manifestJson = JSONObject()
            // Clipped to ManifestParser's own name limit: a longer Nuvio scraper name would otherwise make the whole manifest invalid.
            .put("id", id).put("name", scraper.name.trim().take(ManifestParser.MAX_NAME_CHARS).trim().ifEmpty { scraper.id.take(ManifestParser.MAX_NAME_CHARS) })
            .put("version", "1.0.0").put("apiVersion", 1)
            .put("entry", "plugin.js")
            .put("description", description(scraper.name, repoSlug, warnings))
            .put("hosts", JSONArray(hosts))
            .put("capabilities", JSONArray(listOf("search", "resolve")))
            .toString()

        return NuvioConversionResult(script, manifestJson, hosts, warnings)
    }

    /**
     * The consent sheet shows `description` as is, so the [warnings] ride in it: the spec wants them
     * seen BEFORE installing, and this way the sheet itself needs no change. Built to fit
     * [ManifestParser.MAX_DESCRIPTION_CHARS] (the parser silently truncates past it): origin +
     * license first, then every warning, and only then the generic "hosts were auto-detected" caveat
     * -- the one part dropped when it doesn't fit. [name]/[repoSlug] are clipped so the head plus both
     * warnings always fit (≤ 137 + 1 + 88 + 1 + 65 chars).
     */
    private fun description(name: String, repoSlug: String, warnings: List<String>): String {
        val max = ManifestParser.MAX_DESCRIPTION_CHARS
        val head = "Convertido desde el plugin de Nuvio \"${name.take(30)}\" (${repoSlug.take(40)}); código original GPL-3.0."
        val tail = "Los hosts se detectaron automáticamente y podrían estar incompletos."
        val body = (listOf(head) + warnings).joinToString(" ")
        return if (body.length + 1 + tail.length <= max) "$body $tail" else body.take(max)
    }

    private fun sha256Hex(bytes: ByteArray): String =
        MessageDigest.getInstance("SHA-256").digest(bytes).joinToString("") { "%02x".format(it) }

    /**
     * `getStreams(tmdbId, type, season, episode)` -> `search`/`resolve`. Nuvio has no query-based
     * search of its own (only tmdbId + type + season/episode), so `search` never really searches: it
     * hands back exactly one item that just encodes those four fields for `resolve` to decode later.
     * `resolve` calls the wrapped `getStreams` and picks the first result that isn't torrent-only
     * (Kino's sandbox has no BitTorrent client, spec §6.2) -- `kino.error("unavailable", …)` otherwise.
     *
     * `ref` normally arrives as the JSON string `search` built (Kino quotes an item's `ref` before
     * calling `resolve` with it -- see `PluginContentSource.resolve`), but a plain object is accepted
     * too: nothing about this adapter's own contract requires the string encoding, only Kino's
     * particular caller does.
     *
     * The media type is TRANSLATED, never passed through: Kino's `query.type` is
     * `"movie"`/`"series"`/`"any"` (`PluginContentSource.queryJson`), Nuvio's `getStreams` expects
     * `"movie"`/`"tv"` (its manifests' own `supportedTypes`). `"any"` does reach `resolve` -- `search`
     * encodes whatever type it was given into the ref -- so it's decided there from the episode
     * fields: a season AND an episode mean a TV episode, anything else a movie.
     */
    private val ADAPTER = """

        var __nuvioGetStreams = __nuvioModuleExports.getStreams;

        function __nuvioMediaType(type, season, episode) {
          if (type === "series" || type === "tv") return "tv";
          if (type === "movie") return "movie";
          return (season > 0 && episode > 0) ? "tv" : "movie";
        }

        export async function search(query) {
          if (!query.tmdbId) return [];
          return [{
            id: query.tmdbId + "-" + query.type + "-" + query.season + "-" + query.episode,
            ref: JSON.stringify({ tmdbId: query.tmdbId, type: query.type, season: query.season, episode: query.episode }),
            title: query.q || query.originalTitle || "",
            kind: "movie",
          }];
        }

        export async function resolve(ref) {
          var r = (typeof ref === "string") ? JSON.parse(ref) : ref;
          var streams = (await __nuvioGetStreams(r.tmdbId, __nuvioMediaType(r.type, r.season, r.episode), r.season, r.episode)) || [];
          var playable = streams.filter(function (s) { return s && s.url && !s.infoHash; });
          if (!playable.length) throw kino.error("unavailable", "solo torrents o sin resultados");
          var best = playable[0];
          return { url: best.url, headers: best.headers, mime: best.mime };
        }
    """.trimIndent()
}
